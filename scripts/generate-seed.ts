/**
 * Exports the demo dataset (src/data) to supabase/seed.sql.
 * Run: npm run db:seed:generate — then `supabase db reset` applies migrations + seed.
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { categories } from "../src/data/categories";
import { cities } from "../src/data/cities";
import { bookings, portfolioItems, providers, reviews, serviceRequests, services } from "../src/data/dataset";

/** Deterministic UUID (v5-like) from a string id, so re-running the seed is stable. */
function uuid(key: string): string {
  const h = createHash("sha1").update(`swoj:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
/** Wrap values destined for jsonb columns (arrays would otherwise become text[]). */
class Json {
  constructor(readonly value: unknown) {}
}
const json = (v: unknown) => new Json(v);
const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (v instanceof Json) return `${q(JSON.stringify(v.value))}::jsonb`;
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (values: unknown[]) => `(${values.map(q).join(", ")})`;
const insert = (table: string, cols: string[], rows: unknown[][]) =>
  rows.length ? `insert into public.${table} (${cols.join(", ")}) values\n  ${rows.map(row).join(",\n  ")};\n` : "";

const catId = (slug: string) => uuid(`cat:${slug}`);
const locId = (slug: string) => uuid(`loc:${slug}`);

const out: string[] = ["-- Generated by scripts/generate-seed.ts — do not edit by hand.", "begin;"];

out.push(insert("categories", ["id", "slug", "name", "seo_plural", "person_noun", "icon", "description", "keywords", "faq", "avg_price_from", "sort_order"],
  categories.map((c, i) => [catId(c.slug), c.slug, c.name, c.seoPlural, c.personNoun, c.icon, c.description, c.keywords, json(c.faq), c.avgPriceFrom, i])));

out.push(insert("locations", ["id", "slug", "name", "locative", "lat", "lng", "postal_prefixes", "population"],
  cities.map((c) => [locId(c.slug), c.slug, c.name, c.locative, c.lat, c.lng, c.postalPrefixes, c.population])));

out.push(insert("providers",
  ["id", "slug", "first_name", "last_name", "gender", "headline", "bio", "primary_category_id", "location_id", "district", "service_radius_km",
    "years_experience", "skills", "languages", "experience", "certificates", "provider_type", "company_name", "verified", "response_time_hours",
    "availability", "plan", "featured", "avatar_hue", "member_since", "status"],
  providers.map((p) => [uuid(p.id), p.slug, p.firstName, p.lastName, p.gender, p.headline, p.bio, catId(p.primaryCategory), locId(p.citySlug), p.district,
    p.serviceRadiusKm, p.yearsExperience, p.skills, p.languages, json(p.experience), json(p.certificates), p.providerType, p.companyName, p.verified,
    p.responseTimeHours, p.availability, p.plan, p.featured, p.avatarHue, p.memberSince, "published"])));

out.push(insert("provider_categories", ["provider_id", "category_id"],
  providers.flatMap((p) => p.secondaryCategories.map((c) => [uuid(p.id), catId(c)]))));

out.push(insert("availability", ["provider_id", "weekday", "start_time", "end_time"],
  providers.flatMap((p) => p.weeklyHours.map((h) => [uuid(p.id), h.day, h.from, h.to]))));

out.push(insert("services", ["id", "provider_id", "category_id", "name", "description", "price_from", "price_unit", "duration_min", "duration_max", "sort_order"],
  services.map((s, i) => [uuid(s.id), uuid(s.providerId), catId(s.categorySlug), s.name, s.description, s.priceFrom, s.priceUnit, s.durationMin, s.durationMax, i])));

out.push(insert("service_options", ["id", "service_id", "name", "price"],
  services.flatMap((s) => s.options.map((o) => [uuid(o.id), uuid(s.id), o.name, o.price]))));

out.push(insert("portfolio_items", ["id", "provider_id", "title", "description", "hue", "pattern", "sort_order"],
  portfolioItems.map((p, i) => [uuid(p.id), uuid(p.providerId), p.title, p.description, p.hue, p.pattern, i])));

out.push(insert("reviews", ["id", "provider_id", "author_name", "author_city", "service_name", "rating", "body", "verified_booking", "reply", "created_at"],
  reviews.map((r) => [uuid(r.id), uuid(r.providerId), r.authorName, r.authorCity, r.serviceName, r.rating, r.text, r.verifiedBooking, r.reply, r.date])));

out.push(insert("bookings", ["id", "provider_id", "service_id", "scheduled_date", "scheduled_time", "street", "postal_code", "city", "contact_name", "contact_phone", "status", "total", "created_at"],
  bookings.map((b) => {
    const [street, city] = b.address.split(", ");
    return [uuid(b.id), uuid(b.providerId), uuid(b.serviceId), b.date, b.time, street, "40-001", city, b.clientName, "600000000", b.status, b.total, b.createdAt];
  })));

out.push(insert("requests", ["id", "category_id", "location_id", "title", "description", "preferred_date", "budget", "contact_email", "status", "created_at"],
  serviceRequests.map((r) => [uuid(r.id), catId(r.categorySlug), locId(r.citySlug), r.title, r.description, r.preferredDate, r.budget, `${r.clientName.toLowerCase()}@example.pl`, r.status, r.createdAt])));

// The demo shows a sample of reviews; restore the advertised aggregates after the rating trigger ran.
out.push(...providers.map((p) =>
  `update public.providers set rating_avg = ${p.ratingAvg}, review_count = ${p.reviewCount}, completed_jobs = ${p.completedJobs} where id = '${uuid(p.id)}';`));

out.push("commit;", "");
const target = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(target, out.join("\n"));
console.log(`Wrote ${target}: ${providers.length} providers, ${services.length} services, ${reviews.length} reviews, ${bookings.length} bookings.`);
